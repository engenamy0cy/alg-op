import redis

r = redis.Redis(
    host = 'localhost',
    port=6379,
    decode_response=True
)
r.set("user:l:name", "Michael")

print(r.get("user:l:name")) #michael

# счетчик посещений
r.incr("visits")
print(r.get("visits"))
 

#Команды
#r.set(k,v) созраняет значение
#r.get() получает значение
#r.incr(k) увеличение на 1
#r.decr(k) уменьшение на 1
#r.set(k,v,ex=60) - сохраняет на 60 секунд дальше детриментируем
#r.ttl(k) - оставшееся время от ex
#r.hset(k,mapping=dict) - записывание поля hash
#r.hget(k, field) - читаем одно поле hash
#r.hgetall(k) - читаем все поля
#r.hincrby(k,field,n) увеличивает числовое поле hash
#r.delete(k) - удаляем ключ
#r.exist(k) - проверяет существование ключа
#r.type(k) - узнает тип значения

#Самое главное что нужно понимать по Redis
# Python и Redis - независимые процессы друг от друга
#Python не хранит значение Redis внутри переменной r:
# Это переменная которую представляет клиент, который отправляет
# команды отдельному серверу
# когда мы пишем r.set(...) происходит запись на сервере 
# когда мы вызываем r.get(...) python запрашивает актуальное значение от туда

# Именно поэтому Redis удобен для работы нескольких backend серверов они могут совместно работать
# с одним кешем счетами и оперативныи статусами

